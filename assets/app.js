sendOtpBtn.addEventListener('click', async () => {
  const fullName = fullNameInput.value.trim();
  const mobile = mobileInput.value.trim();
  if (!fullName || !validateMobileForSend(mobile)) {
    showStatus(translate('statusInvalidMobile'), false);
    return;
  }
  clearDebugResponse();
  setButtonLoading(sendOtpBtn, true, translate('statusSendingOtp'));
  showStatus(translate('statusSendingOtp'));
  try {
    const response = await fetch(`${API_BASE}/auth/otp/send`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'include',
      body: JSON.stringify({ fullName, mobileNumber: mobile })
    });
    const responseText = await response.text();
    if (!response.ok) {
      setDebugResponse(responseText || `Error ${response.status}`, false);
      throw new Error(responseText || 'Send OTP failed');
    }
    const otpCode = parseOtpFromResponse(responseText);
    otpSent = true;
    otpSection.classList.remove('d-none');
    generateSection.classList.add('d-none');
    if (otpCode) {
      showStatus(`${translate('statusOtpSent')} ${otpCode}`);
      setDebugResponse(`Test OTP: ${otpCode}`);
    } else {
      showStatus(translate('statusOtpSent'));
      setDebugResponse(responseText || 'OTP send response received.');
    }
  } catch (error) {
    showStatus(translate('statusOtpSendFailed'), false);
    console.error(error);
  } finally {
    setButtonLoading(sendOtpBtn, false);
  }
});

verifyOtpBtn.addEventListener('click', async () => {
  const mobile = mobileInput.value.trim();
  const otp = otpInput.value.trim();
  if (!otpSent || !validateMobileForVerify(mobile) || !validateOtp(otp)) {
    showStatus(translate('statusEnterOtp'), false);
    return;
  }
  clearDebugResponse();
  setButtonLoading(verifyOtpBtn, true, translate('statusVerifyingOtp'));
  showStatus(translate('statusVerifyingOtp'));
  try {
    const response = await fetch(`${API_BASE}/auth/otp/verify`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'include',
      body: JSON.stringify({ fullName: fullNameInput.value.trim(), mobileNumber: mobile, otp })
    });
    const responseText = await response.text();
    let parsed = null;
    try { parsed = JSON.parse(responseText); } catch(e) { parsed = null; }
    if (!response.ok) {
      setDebugResponse(responseText || `Error ${response.status}`, false);
      throw new Error(responseText || 'OTP verification failed');
    }
    // If backend returned an auth token, store it for later requests
    const token = parsed?.token || parsed?.accessToken || parsed?.authToken || parsed?.data?.token || null;
    if (token) {
      authToken = token;
      try { localStorage.setItem('koupanAuthToken', authToken); } catch (e) {}
      setDebugResponse(`OTP verified. Auth token stored. (${token.slice(0,6)}...)`);
    } else {
      setDebugResponse(responseText || 'OTP verify response received.');
    }
    otpVerified = true;
    otpSection.classList.add('d-none');
    generateSection.classList.remove('d-none');
    showStatus(translate('statusOtpVerified'));
  } catch (error) {
    showStatus(error.message || translate('statusOtpVerifyFailed'), false);
    console.error(error);
  } finally {
    setButtonLoading(verifyOtpBtn, false);
  }
});

generateCouponBtn.addEventListener('click', async () => {
  if (!otpVerified) {
    showStatus(translate('statusVerifyBeforeGenerate'), false);
    return;
  }
  const count = parseInt(couponCountInput.value, 10);
  if (isNaN(count) || count < 1) {
    showStatus(translate('statusInvalidCount'), false);
    return;
  }
  setButtonLoading(generateCouponBtn, true, translate('statusGeneratingCoupon'));
  showStatus(translate('statusGeneratingCoupon'));
  try {
    const tokenToUse = authToken || localStorage.getItem('koupanAuthToken') || null;
    const headers = tokenToUse ? { 'Authorization': `Bearer ${tokenToUse}` } : {};
    const response = await fetch(`${API_BASE}/api/coupons/generate-pdf?count=${encodeURIComponent(count)}`, { headers, credentials: 'include' });
    if (!response.ok) {
      const errorText = await response.text();
      setDebugResponse(`Status: ${response.status} ${response.statusText}\n${errorText}`, false);
      throw new Error(errorText || 'Coupon generation failed');
    }
    const blob = await response.blob();
    const url = URL.createObjectURL(blob);
    couponLink.href = url;
    couponLink.classList.remove('d-none');
    showStatus(translate('statusCouponReady'));
    setDebugResponse('Coupon PDF generated successfully.');
  } catch (error) {
    showStatus(error.message || translate('statusCouponFailed'), false);
    console.error(error);
  } finally {
    setButtonLoading(generateCouponBtn, false);
  }
});