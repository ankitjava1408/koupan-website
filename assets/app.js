function setLanguage(lang){
  const dict = translations[lang] || translations.en;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = dict[el.dataset.i18n] || el.textContent; });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = dict[el.dataset.i18nHtml] || el.innerHTML; });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = dict[el.dataset.i18nPlaceholder] || el.placeholder; });
  document.querySelectorAll('[data-lang-btn]').forEach(btn => btn.classList.toggle('active', btn.dataset.langBtn === lang));
  document.documentElement.lang = lang === 'hi' ? 'hi' : 'en';
  localStorage.setItem('koupanLang', lang);
}

