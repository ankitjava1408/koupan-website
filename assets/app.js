function setPhonePreviewActive(active = true) {
  if (!phoneMock) return;

  phoneMock.classList.toggle('is-active', active);
  phoneMock.classList.toggle('is-inactive', !active);
  phoneMock.setAttribute('aria-disabled', String(!active));

  const formControls = phoneMock.querySelectorAll('input, button');
  formControls.forEach((control) => {
    if (active) {
      control.removeAttribute('disabled');
    } else {
      control.setAttribute('disabled', '');
    }
  });

  if (active) {
    requestAnimationFrame(() => {
      requestAnimationFrame(() => {
        fullNameInput.removeAttribute('disabled');
        fullNameInput.focus({ preventScroll: true });
        const end = fullNameInput.value.length;
        fullNameInput.setSelectionRange(end, end);
      });
    });
  }
}

function showStatus(message, success = true) {
  authStatus.textContent = message;
  authStatus.style.color = success ? 'var(--koupan-dark)' : '#d32f2f';
}

function setDebugResponse(message, success = true) {
  if (!debugResponse) return;
  debugResponse.textContent = message;
  debugResponse.style.display = 'block';
  debugResponse.style.color = success ? 'var(--koupan-dark)' : '#d32f2f';
}

function clearDebugResponse() {
  if (!debugResponse) return;
  debugResponse.textContent = '';
  debugResponse.style.display = 'none';
}

function parseOtpFromResponse(text) {
  try {
    const json = JSON.parse(text);
    if (json?.otp) return json.otp;
    if (json?.code) return json.code;
    if (json?.otpCode) return json.otpCode;
    if (json?.message && /\d{4,6}/.test(json.message)) {
      return json.message.match(/\d{4,6}/)[0];
    }
  } catch (e) {
    const match = text.match(/\d{4,6}/);
    return match ? match[0] : null;
  }
  return null;
}

function translate(key) {
  const lang = localStorage.getItem('koupanLang') || 'en';
  return translations[lang]?.[key] || translations.en[key] || key;
}

function validateMobileForSend(value) {
  return /^[0-9]{10}$/.test(value);
}

function validateMobileForVerify(value) {
  return /^[6-9][0-9]{9}$/.test(value);
}

function validateOtp(value) {
  return /^[0-9]{6}$/.test(value);
}

function setButtonLoading(button, loading, label) {
  if (!button) return;
  if (loading) {
    button.dataset.originalHtml = button.dataset.originalHtml || button.innerHTML;
    button.innerHTML = `<span class="spinner-border spinner-border-sm me-2" role="status" aria-hidden="true"></span>${label}`;
    button.disabled = true;
    button.classList.add('btn-loading');
  } else {
    button.innerHTML = button.dataset.originalHtml || button.innerHTML;
    button.disabled = false;
    button.classList.remove('btn-loading');
  }
}

